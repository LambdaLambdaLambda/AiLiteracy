#!/usr/bin/env node
const fs = require('fs');
const path = require('path');

function walk(dir) {
  let results = [];
  const list = fs.readdirSync(dir, { withFileTypes: true });
  for (const d of list) {
    const full = path.join(dir, d.name);
    if (d.isDirectory()) {
      results = results.concat(walk(full));
    } else {
      results.push(full);
    }
  }
  return results;
}

const root = path.join(process.cwd(), 'node_modules');
if (!fs.existsSync(root)) { console.log('No node_modules found, nothing to clean.'); process.exit(0); }

const all = walk(root);
const slides = all.filter(f => f.split(path.sep).pop() === 'slide.html');
console.log(`Found ${slides.length} slide.html files in node_modules`);

let count = 0;
for (const file of slides) {
  try {
    let s = fs.readFileSync(file, 'utf8');
    if (!s.includes('name="slide-title"')) continue;
    // remove the two meta tags we added
    s = s.replace(/\s*<meta[^>]*name=\"slide-title\"[^>]*>\s*/i, '\n');
    s = s.replace(/\s*<meta[^>]*name=\"short-title\"[^>]*>\s*/i, '\n');
    fs.writeFileSync(file, s, 'utf8');
    count++;
  } catch (err) {
    console.error('Error cleaning', file, err.message);
  }
}

console.log(`Cleaned ${count} files in node_modules`);
